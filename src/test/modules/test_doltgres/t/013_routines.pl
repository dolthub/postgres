use strict;
use warnings FATAL => 'all';
use PostgreSQL::Test::Cluster;
use PostgreSQL::Test::Utils;
use Test::More;
my $node=PostgreSQL::Test::Cluster->new('routines');
$node->init(extra=>['--encoding=UTF8','--locale=C']);$node->append_conf('postgresql.conf',"default_table_access_method='dolt_prolly_table'\n");$node->start;
$node->safe_psql('postgres','CREATE DATABASE empty_routines');
my $s=$node->background_psql('postgres',on_error_stop=>0);
sub sql {return $s->query_safe($_[0]);}
sql(q{
CREATE ROLE routine_reader;
CREATE TABLE t(id int PRIMARY KEY,v text) USING dolt_prolly_table;
INSERT INTO t VALUES(1,'main');
CREATE FUNCTION public.f(input text) RETURNS text LANGUAGE plpgsql AS $$BEGIN RETURN input||'_main'; END$$;
CREATE FUNCTION public.rows() RETURNS text LANGUAGE sql STABLE AS $$SELECT v FROM public.t$$;
CREATE FUNCTION secret() RETURNS text LANGUAGE sql AS $$SELECT 'allowed'::text$$;
SELECT dolt_commit('-Am','base');
SELECT dolt_checkout('-b','other');
});
is(sql(q{SELECT f('x')}),'x_main','initial routine captured and callable');
sql(q{CREATE OR REPLACE FUNCTION public.f(input text) RETURNS text LANGUAGE plpgsql AS $$BEGIN RETURN input||'_other'; END$$});
is(sql(q{SELECT f('x')}),'x_other','replacement visible on selected branch');
sql(q{UPDATE t SET v='other'; SELECT dolt_commit('-Am','other'); SELECT dolt_checkout('main')});
is(sql(q{SELECT f('x')}),'x_main','checkout restores function body');
is(sql(q{SELECT rows()}),'main','SQL body uses routine revision');
is(sql(q{SELECT count(*) FROM pg_proc AS OF 'other' WHERE proname='f'}),'1','historical catalog exposes canonical routine');
$s->query_safe(q{PREPARE fcall AS SELECT f('x')});
is($s->query_safe(q{EXECUTE fcall}),'x_main','prepared routine initial branch');
$s->query_safe(q{SELECT dolt_checkout('other')});
is($s->query_safe(q{EXECUTE fcall}),'x_other','prepared routine rebinds after checkout');
$s->query_safe(q{BEGIN; CREATE OR REPLACE FUNCTION f(input text) RETURNS text LANGUAGE sql AS $$SELECT input||'_abort'$$; ROLLBACK});
is($s->query_safe(q{SELECT f('x')}),'x_other','rollback restores definition');
$s->query_safe(q{SET search_path=public,pg_catalog,public; SELECT dolt_checkout('main')});
is($s->query_safe(q{SELECT f('x')}),'x_main','uncached search path resolves canonical main namespace');
$s->query_safe(q{SELECT dolt_checkout('other')});
is($s->query_safe(q{SELECT f('x')}),'x_other','search path cache does not retain old revision handles');
$s->query_safe(q{CREATE FUNCTION write_row() RETURNS text LANGUAGE plpgsql AS $$DECLARE answer text; BEGIN UPDATE t SET v=v||'!'; SELECT v INTO answer FROM t; RETURN answer; END$$});
is($s->query_safe(q{SELECT write_row()}),'other!','working routine writes and reads its own changes');
is($s->query_safe(q{SELECT v FROM t AS OF 'main'}),'main','routine write leaves another branch unchanged');
$s->query_safe(q{CREATE FUNCTION echo_row(t) RETURNS t[] LANGUAGE sql AS $$SELECT ARRAY[$1]$$});
is($s->query_safe(q{SELECT (echo_row(ROW(3,'tuple')::t))[1].v}),'tuple','canonical composite signature and array result');
$s->query_safe(q{CREATE FUNCTION outputs(a int, OUT b int, OUT c text) LANGUAGE sql AS $$SELECT a+1,'out'::text$$});
is($s->query_safe(q{SELECT * FROM outputs(4)}),'5|out','OUT argument names and types survive provider reconstruction');
$s->query_safe(q{CREATE FUNCTION f(input int) RETURNS int LANGUAGE sql AS $$SELECT input+1$$});
is($s->query_safe(q{SELECT f(4),f('x'::text)}),'5|x_other','routine overloads keep distinct canonical signatures');
$s->query_safe(q{CREATE FUNCTION defaults(a int, b int DEFAULT 2, c numeric DEFAULT 1.5 * 2) RETURNS numeric LANGUAGE sql AS $$SELECT a+b+c$$});
is($s->query_safe(q{SELECT defaults(1)||','||defaults(1,10)||','||defaults(1,10,100)}),'6.0,14.0,111','parameter defaults survive provider reconstruction');
is($s->query_safe(q{SELECT pg_get_function_arguments('defaults'::regproc)}),'a integer, b integer DEFAULT 2, c numeric DEFAULT (1.5 * (2)::numeric)','parameter defaults deparse as native');
$s->query_safe(q{CREATE PROCEDURE add_row(i int, w text DEFAULT 'proc') LANGUAGE sql AS $$INSERT INTO t VALUES (i, w)$$; CALL add_row(20); CALL add_row(21, 'given')});
is($s->query_safe(q{SELECT string_agg(v, ',' ORDER BY id) FROM t WHERE id >= 20}),'proc,given','SQL procedure with a default writes the selected branch');
is($s->query_safe(q{SELECT count(*) FROM t AS OF 'main' WHERE id >= 20}),'0','procedure write leaves another branch unchanged');
$s->query_safe(q{CREATE PROCEDURE plpgsql_proc(i int) LANGUAGE plpgsql AS $$BEGIN DELETE FROM t WHERE id = i; END$$; CALL plpgsql_proc(20)});
is($s->query_safe(q{SELECT count(*) FROM t WHERE id >= 20}),'1','PL/pgSQL procedure is callable');
$s->query_safe(q{CREATE FUNCTION altered(x int) RETURNS int LANGUAGE plpgsql AS $$BEGIN RETURN x*2; END$$; ALTER FUNCTION altered(int) IMMUTABLE SET work_mem = '8MB'});
is($s->query_safe(q{SELECT provolatile::text||array_to_string(proconfig,',') FROM pg_proc WHERE proname='altered'}),'iwork_mem=8MB','ALTER FUNCTION changes versioned attributes');
$s->query_safe(q{CREATE SCHEMA moved; ALTER FUNCTION altered(int) SET SCHEMA moved; ALTER FUNCTION moved.altered(int) RENAME TO renamed; ALTER FUNCTION moved.renamed(int) RESET ALL});
is($s->query_safe(q{SELECT moved.renamed(6)||','||(SELECT count(*) FROM pg_proc WHERE proname='altered')||','||(SELECT proconfig IS NULL FROM pg_proc WHERE proname='renamed')}),'12,0,true','SET SCHEMA, RENAME and RESET of a versioned routine');
is($s->query_safe(q{SELECT count(*) FROM pg_proc AS OF 'main' WHERE proname IN ('altered','renamed')}),'0','routine ALTER leaves another branch unchanged');
my ($badout,$bad);
$s->query_safe(q{COMMENT ON FUNCTION moved.renamed(int) IS 'doubles'; COMMENT ON PROCEDURE add_row(int, text) IS 'adds'});
is($s->query_safe(q{SELECT obj_description('moved.renamed'::regproc, 'pg_proc')||','||obj_description('add_row'::regproc, 'pg_proc')}),'doubles,adds','COMMENT ON FUNCTION and PROCEDURE');
$s->query_safe(q{ALTER FUNCTION moved.renamed(int) RENAME TO commented});
is($s->query_safe(q{SELECT obj_description('moved.commented'::regproc, 'pg_proc')}),'doubles','a routine keeps its comment when renamed');
is($s->query_safe(q{SELECT (SELECT count(*) FROM pg_description WHERE description='adds')||','||(SELECT count(*) FROM pg_description AS OF 'main' WHERE description='adds')}),'1,0','a comment is branched');

# ---- SQL-standard bodies ----
$s->query_safe(q{CREATE FUNCTION plus_one(x int) RETURNS int LANGUAGE sql IMMUTABLE RETURN x + 1;
CREATE FUNCTION named_rows(m int) RETURNS bigint LANGUAGE sql STABLE BEGIN ATOMIC SELECT count(*) * m FROM t; END;
CREATE PROCEDURE add_next(i int) LANGUAGE sql BEGIN ATOMIC INSERT INTO t VALUES (plus_one(i), 'atomic'); END});
$s->query_safe(q{CALL add_next(40)});
is($s->query_safe(q{SELECT plus_one(1)||','||named_rows(10)||','||(SELECT v FROM t WHERE id=41)}),'2,30,atomic','RETURN and BEGIN ATOMIC bodies run');
is($s->query_safe(q{SELECT pg_get_function_sqlbody('add_next'::regproc)}),"BEGIN ATOMIC\n INSERT INTO t (id, v)\n   VALUES (plus_one(add_next.i), 'atomic'::text);\nEND",'a SQL-standard body deparses as native');
($badout,$bad)=$s->query(q{DROP FUNCTION plus_one(int)});
is($bad,1,'a SQL-standard body protects the routines it calls');like($s->{stderr},qr/function add_next\(integer\) depends on function plus_one\(integer\)/,'a SQL-standard body protects the routines it calls diagnostic');$s->{stderr}='';
$s->query_safe(q{ALTER FUNCTION plus_one(int) RENAME TO incremented; ALTER TABLE t RENAME COLUMN v TO w});
is($s->query_safe(q{SELECT pg_get_function_sqlbody('add_next'::regproc)}),"BEGIN ATOMIC\n INSERT INTO t (id, w)\n   VALUES (incremented(add_next.i), 'atomic'::text);\nEND",'renames rewrite a SQL-standard body');
$s->query_safe(q{CALL add_next(42); ALTER TABLE t RENAME COLUMN w TO v});
is($s->query_safe(q{SELECT count(*) FROM t WHERE v='atomic'}),'2','a rewritten body runs');
is($s->query_safe(q{SELECT count(*) FROM pg_proc AS OF 'main' WHERE proname IN ('plus_one','named_rows','add_next')}),'0','SQL-standard routines are branched');
($badout,$bad)=$s->query(q{CREATE OR REPLACE FUNCTION f(input text) RETURNS int LANGUAGE sql AS $$SELECT 1$$});
is($bad,1,'native replacement rejects changing return type');$s->{stderr}='';
is($s->query_safe(q{SELECT f('x')}),'x_other','failed replacement leaves definition intact');
($badout,$bad)=$s->query(q{DROP TABLE t});
is($bad,1,'table drop cannot publish dangling routine signature');$s->{stderr}='';
is($s->query_safe(q{SELECT (echo_row(ROW(3,'kept')::t))[1].v}),'kept','rejected table drop preserves signature');
# TODO: routine privileges, once the ownership and ACL design decides what
# versioned storage records about roles.
is($s->query_safe(q{SELECT secret()}),'allowed','captured routine is callable');
is($s->query_safe(q{SELECT routine_name||':'||data_type FROM information_schema.routines WHERE routine_schema='public' AND routine_name='secret'}),'secret:text','information schema routines uses canonical definitions');
$s->query_safe(q{DROP FUNCTION f(text)});
is($s->query_safe(q{SELECT count(*) FROM pg_proc WHERE proname='f' AND proargtypes='25'::oidvector}),'0','routine drop removes only current definition');
is($s->query_safe(q{SELECT count(*) FROM pg_proc AS OF 'main' WHERE proname='f'}),'1','routine drop retains other branch and history');
$s->query_safe(q{SELECT dolt_checkout('main')});
is($s->query_safe(q{SELECT f('x')}),'x_main','other branch routine survives drop');
# An event trigger is the database's, so the function it calls stays native.
$s->query_safe(q{CREATE TABLE logins(who text) USING heap; CREATE FUNCTION on_login() RETURNS event_trigger LANGUAGE plpgsql AS $$BEGIN INSERT INTO logins VALUES (session_user); END$$; CREATE EVENT TRIGGER login_trigger ON login EXECUTE FUNCTION on_login(); ALTER EVENT TRIGGER login_trigger ENABLE ALWAYS});
is($node->safe_psql('postgres',q{SELECT count(*) FROM logins}),'1','an event trigger calls a native PL/pgSQL function');
is($s->query_safe(q{SELECT count(*) FROM pg_proc AS OF 'main' WHERE proname='on_login'}),'1','which every branch sees');
$s->query_safe(q{CREATE TABLE after_login(id int); DROP TABLE after_login});
pass('a login trigger, which DDL never fires, leaves versioned DDL available');
$s->query_safe(q{DROP EVENT TRIGGER login_trigger; DROP FUNCTION on_login()});
$s->quit;
my $e=$node->background_psql('empty_routines',on_error_stop=>0);
# A database versions its routines once it has prolly storage.
$e->query_safe(q{CREATE TABLE anchor(id int) USING dolt_prolly_table; CREATE FUNCTION f(input text) RETURNS text LANGUAGE plpgsql AS $$BEGIN RETURN input; END$$; SELECT dolt_add('.')});
my ($out,$failed)=$e->query(q{SELECT length(dolt_commit('-m','scalar-wrapped commit'))});
is($failed,0,'standalone scalar-wrapped version-control commit');$e->{stderr}='';
$e->query_safe(q{SELECT dolt_checkout('-b','other')});
($out,$failed)=$e->query(q{CREATE OR REPLACE FUNCTION f(input text) RETURNS text LANGUAGE plpgsql AS $$BEGIN RETURN input||'!'; END$$});
is($failed,0,'initialized public namespace supports branch-local routine replacement');$e->{stderr}='';
$e->query_safe(q{SELECT dolt_checkout('main')});
$e->query_safe(q{CREATE OR REPLACE FUNCTION f(input text) RETURNS text LANGUAGE plpgsql AS $$BEGIN RETURN input||'!'; END$$});
is($e->query_safe(q{SELECT f('x')}),'x!','routine replacement on main remains independent');
$e->quit;$node->stop;done_testing();
