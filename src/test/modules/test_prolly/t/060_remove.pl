use strict;
use warnings FATAL => 'all';
use PostgreSQL::Test::Cluster;
use PostgreSQL::Test::Utils;
use Test::More;
my $node=PostgreSQL::Test::Cluster->new('remove');
$node->init(extra=>['--encoding=UTF8','--locale=C']);$node->start;
sub sql { $node->safe_psql('postgres',$_[0]); }
sub fails { my($q,$pattern,$label)=@_;my($ret,$out,$err)=$node->psql('postgres',$q);isnt($ret,0,$label);like($err,$pattern,"$label diagnostic"); }
fails(q{SELECT dolt_rm()},qr/Nothing specified/,'empty arguments are rejected');
fails(q{SELECT dolt_rm('--cached','--cached')},qr/Nothing specified/,'flags alone cannot remove everything');
sql(q{CREATE TABLE t(id int PRIMARY KEY,v text) USING dolt_prolly_table; INSERT INTO t VALUES(1,'base'); SELECT dolt_commit('-Am','base')});
sql(q{UPDATE t SET v='dirty'});
fails(q{SELECT dolt_rm('t')},qr/unstaged changes/,'dirty data cannot be removed');
is(sql(q{SELECT v FROM t}), 'dirty','failed removal preserves data');
sql(q{SELECT dolt_add('t')});
fails(q{SELECT dolt_rm('t')},qr/unstaged changes/,'staged modifications of tracked table still require commit');
sql(q{SELECT dolt_rm('t','--cached')});
is(sql(q{SELECT staged,status FROM dolt_status WHERE table_name='public.t' ORDER BY staged DESC}), "t|deleted\nf|new table", 'cached removal retains working table');
sql(q{SELECT dolt_reset('--hard'); CREATE TABLE new_t(id int) USING dolt_prolly_table; SELECT dolt_add('new_t')});
fails(q{SELECT dolt_rm('new_t')},qr/changes saved in the index/,'new staged table is protected');
sql(q{SELECT dolt_rm('new_t','--cached')});
is(sql(q{SELECT count(*) FROM new_t}), '0','cached removal retains newly staged table');
sql(q{CREATE TABLE parent(id int PRIMARY KEY) USING dolt_prolly_table; SELECT dolt_commit('-Am','parent'); CREATE TABLE child(id int REFERENCES parent) USING dolt_prolly_table});
fails(q{SELECT dolt_rm('parent','--cached')},qr/referenced from table public.child/,'working-only foreign key protects cached removal');
sql(q{SELECT dolt_add('child'); DROP TABLE child});
fails(q{SELECT dolt_rm('parent','--cached')},qr/referenced from table public.child/,'staged-only foreign key protects cached removal');
sql(q{SELECT dolt_rm('parent','child','--cached')});
is(sql(q{SELECT count(*) FROM parent}), '0','cached joint removal leaves working parent');
sql(q{SELECT dolt_reset('--hard')});
my $readonly=$node->background_psql('postgres',on_error_stop=>0);
$readonly->query_safe(q{SET default_transaction_read_only=on});
my($out,$failed)=$readonly->query(q{SELECT dolt_rm('parent')});
is($failed,1,'read-only removal rejected');like($readonly->{stderr},qr/read-only transaction/,'read-only diagnostic');$readonly->{stderr}='';$readonly->quit;
is(sql(q{SELECT count(*) FROM parent}), '0','read-only rejection preserves table');
sql(q{SELECT dolt_rm('parent')});
is(sql(q{SELECT status FROM dolt_status WHERE table_name='public.parent'}), 'deleted','clean removal stages deletion');
sql(q{SELECT dolt_reset('--hard'); CREATE TABLE child(id int REFERENCES parent) USING dolt_prolly_table; SELECT dolt_commit('-Am','child')});
sql(q{UPDATE t SET v='dirty'});
fails(q{SELECT dolt_rm('parent','t')},qr/unstaged changes/,'mixed removal preflights all arguments');
is(sql(q{SELECT count(*) FROM parent}), '0','mixed removal failure preserves earlier table');
is(sql(q{SELECT count(*) FROM dolt_status WHERE table_name='public.parent'}),'0','failed removal does not stage earlier table');
sql(q{SELECT dolt_rm('parent','child')});
is(sql(q{SELECT count(*) FROM dolt_status WHERE staged AND status='deleted' AND table_name IN ('public.parent','public.child')}),'2','joint parent and child removal succeeds without cascade');
sql(q{SELECT dolt_reset('--hard'); DROP TABLE child; SELECT dolt_rm('child','--cached')});
is(sql(q{SELECT status FROM dolt_status WHERE staged AND table_name='public.child'}),'deleted','cached removal accepts table already absent from working');
$node->stop;done_testing();
