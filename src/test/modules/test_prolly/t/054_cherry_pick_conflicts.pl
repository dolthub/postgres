use strict;
use warnings FATAL => 'all';
use PostgreSQL::Test::Cluster;
use PostgreSQL::Test::Utils;
use Test::More;
my $node=PostgreSQL::Test::Cluster->new('cherry_conflicts');
$node->init(extra=>['--encoding=UTF8','--locale=C']);
$node->start;
sub sql { $node->safe_psql('postgres',$_[0]); }
sql(q{CREATE TABLE t(id int PRIMARY KEY,v text) USING dolt_prolly_table; INSERT INTO t VALUES(1,'base'),(2,'base')});
sql(q{SELECT dolt_commit('-Am','base')});
sql(q{SELECT dolt_branch('side')});
my $side=$node->background_psql('postgres');
$side->query_safe(q{SELECT dolt_checkout('side')});
$side->query_safe(q{UPDATE t SET v='theirs'});
$side->query_safe(q{SELECT dolt_commit('-Am','source edits')});
$side->quit;
sql(q{UPDATE t SET v='ours' WHERE id=1});
sql(q{SELECT dolt_commit('-Am','target edit')});
my $head=sql(q{SELECT dolt_hashof('HEAD')});
is(sql(q{SELECT hash,data_conflicts,schema_conflicts,constraint_violations FROM dolt_cherry_pick('side')}),'|1|0|0','cherry-pick reports durable conflicts without error');
is(sql(q{SELECT dolt_hashof('HEAD')}),$head,'conflicting cherry-pick does not move HEAD');
is(sql(q{SELECT id,v FROM t ORDER BY id}),"1|ours\n2|theirs",'nonconflicting edits retained');
is(sql(q{SELECT count(*) FROM dolt_conflicts_t}),'1','row conflict is inspectable');
is(sql(q{SELECT count(*) FROM dolt_diff('HEAD','STAGED','t')}),'0','conflicting changes not staged');
$node->restart;
is(sql(q{SELECT count(*) FROM dolt_conflicts_t}),'1','conflicts survive restart');
sql(q{SELECT dolt_conflicts_resolve('--ours','t')});
is(sql(q{SELECT count(*) FROM dolt_conflicts_t}),'0','shared resolver resolves cherry-pick conflict');
is(sql(q{SELECT hash,data_conflicts FROM dolt_cherry_pick('--abort')}),'|0','abort works after conflict metadata update');
is(sql(q{SELECT id,v FROM t ORDER BY id}),"1|ours\n2|base",'abort restores all pre-pick rows');
is(sql(q{SELECT count(*) FROM dolt_status}),'0','abort restores clean workspace');
is(sql(q{SELECT data_conflicts FROM dolt_cherry_pick('side')}),'1','cherry-pick can be retried');
sql(q{SELECT dolt_conflicts_resolve('--theirs','t')});
sql(q{SELECT dolt_commit('-Am','resolved cherry-pick')});
is(sql(q{SELECT parents FROM dolt_log('--parents','-n','1')}),$head,'resolved cherry-pick has exactly its original single parent');
is(sql(q{SELECT id,v FROM t ORDER BY id}),"1|theirs\n2|theirs",'resolution commits selected source rows');
my($status,$out,$err)=$node->psql('postgres',q{SELECT dolt_cherry_pick('--abort')});
isnt($status,0,'completed cherry-pick cannot be aborted');
like($err,qr/no cherry-pick to abort/,'abort diagnostic');
$node->stop;
done_testing();
