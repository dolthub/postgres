use strict;
use warnings FATAL => 'all';
use PostgreSQL::Test::Cluster;
use PostgreSQL::Test::Utils;
use Test::More;
my $node = PostgreSQL::Test::Cluster->new('revert_workflows');
$node->init(extra => ['--encoding=UTF8','--locale=C']);
$node->start;
sub sql { $node->safe_psql('postgres',$_[0]); }
sql(q{CREATE TABLE t(id int PRIMARY KEY,v int) USING dolt_prolly_table; INSERT INTO t VALUES(1,1)});
sql(q{SELECT dolt_commit('-Am','seed')});
sql(q{INSERT INTO t VALUES(2,2)});
sql(q{SELECT dolt_commit('-Am','insert two')});
sql(q{INSERT INTO t VALUES(3,3)});
sql(q{SELECT dolt_commit('-Am','insert three')});
sql(q{SELECT dolt_revert('HEAD','HEAD~1')});
is(sql(q{SELECT id FROM t ORDER BY id}), '1', 'multi-revert binds relative revisions before publishing');
is(sql(q{SELECT message FROM dolt_log LIMIT 2}), "Revert \"insert two\"\nRevert \"insert three\"", 'each requested revision receives one revert commit');
sql(q{INSERT INTO t VALUES(2,2),(3,3)});
sql(q{SELECT dolt_commit('-Am','seed series')});
for my $id (1..3) {
 sql("UPDATE t SET v=$id*10 WHERE id=$id");
 sql("SELECT dolt_commit('-Am','change $id')");
}
sql(q{UPDATE t SET v=v+1 WHERE id IN (2,3)});
sql(q{SELECT dolt_commit('-Am','clobber')});
my $original = sql(q{SELECT dolt_hashof('HEAD')});
is(sql(q{SELECT hash,data_conflicts FROM dolt_revert('HEAD~3','HEAD~2','HEAD~1')}), '|1', 'series stops at first conflict');
is(sql(q{SELECT v FROM t WHERE id=1}), '1', 'earlier clean revert remains published');
is(sql(q{SELECT message FROM dolt_log LIMIT 1}), 'Revert "change 1"', 'first revert commit is visible');
is(sql(q{SELECT base_v,our_v,their_v FROM dolt_conflicts_t}), '20|21|2', 'revert conflict uses reverted commit as base and its parent as theirs');
$node->restart;
sql(q{SELECT dolt_revert('--abort')});
is(sql(q{SELECT dolt_hashof('HEAD')}), $original, 'abort restores original series HEAD across restart');
is(sql(q{SELECT id,v FROM t ORDER BY id}), "1|10\n2|21\n3|31", 'abort restores original series rows');
sql(q{SELECT dolt_revert('HEAD~3','HEAD~2','HEAD~1')});
is(sql(q{SELECT hash,data_conflicts FROM dolt_revert('--continue')}), '|1', 'unresolved continue returns counts');
sql(q{DELETE FROM dolt_conflicts_t; SELECT dolt_add('t')});
is(sql(q{SELECT hash,data_conflicts FROM dolt_revert('--continue')}), '|1', 'continue publishes one resolution and proceeds to next conflict');
is(sql(q{SELECT message FROM dolt_log LIMIT 1}), 'Revert "change 2"', 'resolution retains original reverted message');
$node->restart;
sql(q{DELETE FROM dolt_conflicts_t; SELECT dolt_add('t')});
is(sql(q{SELECT data_conflicts FROM dolt_revert('--continue')}), '0', 'second continuation completes retained queue after restart');
is(sql(q{SELECT id,v FROM t ORDER BY id}), "1|1\n2|21\n3|31", 'completed series preserves chosen resolutions');
is(sql(q{SELECT count(*) FROM dolt_status}), '0', 'completed series clears merge state');
sql(q{CREATE TABLE unrelated(id int PRIMARY KEY) USING dolt_prolly_table});
sql(q{SELECT dolt_commit('-Am','unrelated schema')});
sql(q{INSERT INTO t VALUES(4,4)});
sql(q{SELECT dolt_commit('-Am','insert four')});
sql(q{INSERT INTO unrelated VALUES(1)});
sql(q{SELECT dolt_revert('HEAD')});
is(sql(q{SELECT id FROM unrelated}), '1', 'revert preserves disjoint unstaged edits');
is(sql(q{SELECT count(*) FROM unrelated AS OF 'HEAD'}), '0', 'disjoint edits are not included in revert commit');
sql(q{SELECT dolt_add('unrelated')});
my ($status,$out,$err)=$node->psql('postgres',q{SELECT dolt_revert('HEAD')});
like($err,qr/cannot revert with uncommitted changes/, 'even disjoint staged changes prevent revert');
sql(q{SELECT dolt_reset('unrelated'); INSERT INTO t VALUES(4,4)});
($status,$out,$err)=$node->psql('postgres',q{SELECT dolt_revert('HEAD')});
like($err,qr/local changes would be overwritten by revert/, 'overlapping local changes reject revert even when equal to its result');
is(sql(q{SELECT v FROM t WHERE id=4}), '4', 'failed revert preserves existing edits');
$node->stop;
done_testing();
