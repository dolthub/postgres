use strict;
use warnings FATAL => 'all';
use PostgreSQL::Test::Cluster;
use PostgreSQL::Test::Utils;
use Test::More;
my $node = PostgreSQL::Test::Cluster->new('inheritance');
$node->init(extra => ['--encoding=UTF8', '--locale=C']);
$node->append_conf('postgresql.conf', "default_table_access_method='dolt_prolly_table'\nautovacuum=off\n");
$node->start;
sub sql { $node->safe_psql('postgres', $_[0]); }
sub fails {
 my ($query, $pattern, $name) = @_;
 my ($status, $out, $err) = $node->psql('postgres', $query);
 isnt($status, 0, $name); like($err, $pattern, "$name diagnostic");
}
sql(q{CREATE TABLE parent(a int CHECK(a>0)); INSERT INTO parent VALUES(1);
 CREATE TABLE child(b text) INHERITS(parent); INSERT INTO child VALUES(2,'child')});
is(sql(q{SELECT a FROM parent ORDER BY a}), "1\n2", 'parent scans child storage');
is(sql(q{SELECT a FROM ONLY parent}), '1', 'ONLY excludes child');
is(sql(q{SELECT attislocal,attinhcount FROM pg_attribute WHERE attrelid='child'::regclass AND attname='a'}), 'f|1', 'inherited attribute metadata');
is(sql(q{SELECT conislocal,coninhcount FROM pg_constraint WHERE conrelid='child'::regclass AND contype='c'}), 'f|1', 'inherited constraint metadata');
sql(q{SELECT dolt_commit('-Am','inheritance'); SELECT dolt_branch('feature')});
is(sql(q{SELECT status FROM dolt_checkout('feature'); UPDATE parent SET a=a+10; SELECT a FROM parent ORDER BY a}), "0\n11\n12", 'inherited UPDATE on feature');
is(sql(q{SELECT a FROM parent ORDER BY a}), "1\n2", 'main retains original parent and child rows');
sql(q{SELECT dolt_checkout('feature'); SELECT dolt_commit('-Am','update'); SELECT dolt_checkout('main'); SELECT dolt_merge('feature')});
is(sql(q{SELECT a FROM parent ORDER BY a}), "11\n12", 'merge includes child data');
$node->restart;
is(sql(q{SELECT a FROM parent ORDER BY a}), "11\n12", 'inheritance survives restart');
sql(q{CREATE INDEX child_a ON child(a); SELECT dolt_commit('-Am','index'); SELECT dolt_branch('before_ddl')});
sql(q{ALTER TABLE parent ADD COLUMN n int DEFAULT 7 NOT NULL});
is(sql(q{SELECT a,n FROM parent ORDER BY a}), "11|7\n12|7", 'recursive added default rewrites each table');
is(sql(q{SELECT a,b,n FROM child}), '12|child|7', 'child local columns retain their layout');
sql(q{ALTER TABLE parent ALTER COLUMN a TYPE bigint USING a+100});
is(sql(q{SELECT a,n FROM parent ORDER BY a}), "111|7\n112|7", 'recursive type rewrite uses each child source');
sql(q{ALTER TABLE parent DROP COLUMN n});
is(sql(q{SELECT a,b FROM child}), '112|child', 'recursive drop preserves child data');
is(sql(q{SELECT status FROM dolt_checkout('before_ddl'); SELECT a,b FROM child}), "0\n12|child", 'other branch retains old schema and data');
sql(q{ALTER TABLE child NO INHERIT parent});
is(sql(q{SELECT a FROM parent}), '111', 'NO INHERIT excludes child');
sql(q{ALTER TABLE child INHERIT parent});
is(sql(q{SELECT a FROM parent ORDER BY a}), "111\n112", 'INHERIT attaches existing child');
sql(q{ALTER TABLE parent RENAME TO renamed_parent});
is(sql(q{SELECT a FROM renamed_parent ORDER BY a}), "111\n112", 'parent rename preserves edges');
sql(q{BEGIN; ALTER TABLE renamed_parent ADD COLUMN rolled_back int DEFAULT 3; ROLLBACK});
is(sql(q{SELECT count(*) FROM pg_attribute WHERE attrelid='child'::regclass AND attname='rolled_back'}), '0', 'recursive DDL rolls back');
sql(q{BEGIN; TRUNCATE renamed_parent; ROLLBACK});
is(sql(q{SELECT a FROM renamed_parent ORDER BY a}), "111\n112", 'inherited TRUNCATE rolls back');
sql(q{DELETE FROM renamed_parent WHERE a=112});
is(sql(q{SELECT count(*) FROM child}), '0', 'inherited DELETE reaches child storage');
sql(q{CREATE TABLE other(a bigint CHECK(a>0)); CREATE TABLE diamond(c int) INHERITS(renamed_parent, other); INSERT INTO diamond VALUES(200,9)});
is(sql(q{SELECT attinhcount FROM pg_attribute WHERE attrelid='diamond'::regclass AND attname='a'}), '2', 'multiple inheritance preserves counts');
is(sql(q{SELECT a FROM renamed_parent ORDER BY a}), "111\n200", 'multiple inheritance contributes rows');
fails(q{ALTER TABLE diamond DROP CONSTRAINT parent_a_check}, qr/inherited constraint/, 'cannot drop inherited check directly');
sql(q{ALTER TABLE diamond NO INHERIT renamed_parent});
is(sql(q{SELECT count(*) FROM pg_inherits WHERE inhrelid='diamond'::regclass}), '1', 'detach first of multiple parents');
sql(q{CREATE TABLE grandchild(d int) INHERITS(child); INSERT INTO grandchild VALUES(300,'grand',1);
 ALTER TABLE renamed_parent RENAME a TO renamed_a});
is(sql(q{SELECT renamed_a,b,d FROM grandchild}), '300|grand|1', 'column rename reaches grandchild');
is(sql(q{SELECT a FROM parent AS OF 'before_ddl' ORDER BY a}), "11\n12", 'historical parent expands historical child definitions');
is(sql(q{SELECT p.a,c.renamed_a FROM parent AS OF 'before_ddl' p CROSS JOIN renamed_parent c ORDER BY 1,2}), "11|111\n11|300\n12|111\n12|300", 'one query combines old and current inheritance graphs');
sql(q{SELECT dolt_commit('-Am','inherited DDL'); SELECT dolt_branch('parallel')});
my $left = $node->background_psql('postgres');
my $right = $node->background_psql('postgres');
$left->query_safe(q{SELECT dolt_checkout('main')});
$right->query_safe(q{SELECT dolt_checkout('parallel'); SET lock_timeout='2s'});
$left->query_safe(q{BEGIN; ALTER TABLE renamed_parent ADD COLUMN left_value int DEFAULT 5});
$right->query_safe(q{ALTER TABLE renamed_parent ADD COLUMN right_value int DEFAULT 6});
$left->query_safe('COMMIT');
is($right->query_safe(q{SELECT right_value FROM grandchild}), '6', 'other branch DDL does not wait for uncommitted inherited DDL');
is($left->query_safe(q{SELECT left_value FROM grandchild}), '5', 'both branches publish independent recursive changes');
$left->quit; $right->quit;
sql(q{CREATE VIEW inherited_view AS SELECT left_value FROM grandchild; ALTER TABLE renamed_parent DROP COLUMN left_value CASCADE});
is(sql(q{SELECT renamed_a,b,d FROM grandchild}), '300|grand|1', 'recursive CASCADE remaps child tuples');
is(sql(q{SELECT count(*) FROM pg_class WHERE relname='inherited_view'}), '0', 'CASCADE removes dependent view from the root');
sql(q{CREATE TABLE cleanup(a int); DROP TABLE IF EXISTS cleanup, cleanup_missing; CREATE TABLE cleanup(a int)});
is(sql(q{SELECT count(*) FROM cleanup}), '0', 'DROP IF EXISTS handles missing siblings of versioned tables');
$node->stop;
done_testing();
