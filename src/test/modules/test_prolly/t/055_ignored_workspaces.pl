use strict;
use warnings FATAL => 'all';
use PostgreSQL::Test::Cluster;
use PostgreSQL::Test::Utils;
use Test::More;
my $node = PostgreSQL::Test::Cluster->new('ignored_workspaces');
$node->init(extra => ['--encoding=UTF8', '--locale=C']);
$node->start;
sub sql { $node->safe_psql('postgres', $_[0]); }
sql(q{INSERT INTO dolt_ignore VALUES ('generated_*',true);
CREATE TABLE generated_foo(id int PRIMARY KEY) USING dolt_prolly_table;
CREATE TABLE generated_bar(id int PRIMARY KEY) USING dolt_prolly_table;
INSERT INTO generated_foo VALUES(1); INSERT INTO generated_bar VALUES(1)});
sql(q{SELECT dolt_add('generated_foo')});
is(sql(q{SELECT count(*) FROM dolt_status WHERE staged AND table_name='public.generated_foo'}), '0', 'ordinary named add respects ignore rules');
sql(q{SELECT dolt_add('--force','generated_bar')});
is(sql(q{SELECT count(*) FROM dolt_status WHERE staged AND table_name='public.generated_bar'}), '1', 'force adds ignored table');
sql(q{SELECT dolt_commit('-Am','tracked generated table')});
sql(q{INSERT INTO generated_bar VALUES(2); SELECT dolt_add('-A')});
is(sql(q{SELECT count(*) FROM dolt_status WHERE staged AND table_name='public.generated_bar'}), '1', 'subsequent ordinary add stages tracked ignored-name table');
is(sql(q{SELECT count(*) FROM dolt_status WHERE staged AND table_name='public.generated_foo'}), '0', 'add all leaves untracked ignored table unstaged');
sql(q{SELECT dolt_add('-f','--all')});
is(sql(q{SELECT count(*) FROM dolt_status WHERE staged AND table_name='public.generated_foo'}), '1', 'force all stages ignored tables');
my ($status,$out,$err) = $node->psql('postgres',q{SELECT dolt_add('--force')});
isnt($status,0,'force requires targets');
like($err,qr/requires/, 'missing target diagnostic');
sql(q{SELECT dolt_reset('generated_foo')});
sql(q{CREATE TABLE t(id int PRIMARY KEY,v text) USING dolt_prolly_table; INSERT INTO t VALUES(1,'base')});
sql(q{SELECT dolt_commit('-Am','base')});
is(sql(q{SELECT table_name,staged,status,ignored FROM dolt_status_ignored}), 'public.generated_foo|f|new table|t', 'ignored status exposes excluded table');
is(sql(q{SELECT count(*) FROM dolt_status}), '0', 'ordinary status excludes ignored table');
sql(q{SELECT dolt_branch('side')});
my $side = $node->background_psql('postgres');
$side->query_safe(q{SELECT dolt_checkout('side'); UPDATE t SET v='theirs'});
$side->query_safe(q{SELECT dolt_commit('-Am','source edit')});
$side->quit;
sql(q{UPDATE t SET v='ours'});
sql(q{SELECT dolt_commit('-Am','target edit')});
is(sql(q{SELECT data_conflicts FROM dolt_cherry_pick('side')}), '1', 'ignored untracked table does not block cherry-pick');
is(sql(q{SELECT id FROM generated_foo}), '1', 'ignored table survives conflicting pick');
sql(q{INSERT INTO generated_foo VALUES(2); INSERT INTO generated_bar VALUES(3)});
$node->restart;
sql(q{SELECT dolt_cherry_pick('--abort')});
is(sql(q{SELECT id FROM generated_foo ORDER BY id}), "1\n2", 'abort preserves ignored edits across restart');
is(sql(q{SELECT id FROM generated_bar ORDER BY id}), "1\n2", 'abort reverts force-added tracked edits');
is(sql(q{SELECT v FROM t}), 'ours', 'abort restores tracked rows');
is(sql(q{SELECT table_name,staged,status,ignored FROM dolt_status_ignored}), 'public.generated_foo|f|new table|t', 'abort retains ignored status only');
sql(q{SELECT dolt_cherry_pick('side')});
sql(q{SELECT dolt_conflicts_resolve('--theirs','t')});
sql(q{SELECT dolt_cherry_pick('--continue')});
is(sql(q{SELECT v FROM t}), 'theirs', 'continue publishes selected resolution');
is(sql(q{SELECT id FROM generated_foo ORDER BY id}), "1\n2", 'continue retains ignored rows');
is(sql(q{SELECT table_name FROM dolt_status_ignored WHERE ignored}), 'public.generated_foo', 'continue does not commit ignored table');
$node->stop;
done_testing();
