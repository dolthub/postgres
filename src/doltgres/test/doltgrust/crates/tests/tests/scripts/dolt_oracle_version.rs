//! The `version` cases of the retired Doltlite oracle corpus, with expectations recorded from Dolt's main branch.

use harness::oid::*;
use harness::script::Cell::{Any, Null, Text as T};
use harness::script::{A, Column, Diagnostic, Dolt, E, Expected, S, ScriptTest, ScriptTestAssertion, run_scripts};

#[test]
fn test_version() {
    run_scripts(&[
        ScriptTest {
            name: r#"dt_basic_dt"#,
            intent: r#"Doltlite oracle case: dt basic dt."#,
            set_up_script: &[],
            assertions: &[
                ScriptTestAssertion {
                    query: r#"CREATE DATABASE "db0";"#,
                    expected: Expected::Ok,
                    ..A
                },
                ScriptTestAssertion {
                    query: r#"SELECT DOLT_VERSION();"#,
                    expected: Expected::Rows {
                        columns: &[Column(r#"dolt_version"#, TEXT)],
                        rows: &[
                            &[T(r#"0.1.0"#)],
                        ],
                        tag: "SELECT 1",
                    },
                    client: "s2",
                    database: r#"db0"#,
                    dolt: Some(Dolt::MySqlOnly(r#"Doltgrust reports its own version"#)),
                    ..A
                },
                ScriptTestAssertion {
                    query: r#""#,
                    expected: Expected::Ok,
                    client: "s2",
                    close_client: true,
                    ..A
                },
            ],
            ..S
        },
        ScriptTest {
            name: r#"dt_one_arg_dt_err"#,
            intent: r#"Doltlite oracle case: dt one arg dt err."#,
            set_up_script: &[],
            assertions: &[
                ScriptTestAssertion {
                    query: r#"CREATE DATABASE "db0";"#,
                    expected: Expected::Ok,
                    ..A
                },
                ScriptTestAssertion {
                    query: r#"SELECT DOLT_VERSION('x');"#,
                    expected: Expected::Error(Diagnostic { code: "42883", message: r#"function dolt_version(unknown) does not exist"#, hint: r#"No function matches the given name and argument types. You might need to add explicit type casts."#, position: 8, ..E }),
                    client: "s2",
                    database: r#"db0"#,
                    ..A
                },
                ScriptTestAssertion {
                    query: r#""#,
                    expected: Expected::Ok,
                    client: "s2",
                    close_client: true,
                    ..A
                },
            ],
            ..S
        },
    ]);
}
