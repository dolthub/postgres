# Writes the C header of a crate's include_str! texts: each named file's
# bytes as an array of that name, so the C reads the same text the Rust
# compiles in.
#
# usage: embed.pl <output> <name> <file> [<name> <file>]...

use strict;
use warnings FATAL => 'all';
use File::Basename;

my ($output, @pairs) = @ARGV;
die "usage: embed.pl <output> <name> <file> [<name> <file>]...\n"
  if !@pairs || @pairs % 2;

open(my $out, '>', $output) or die "cannot write $output: $!";
binmode($out);
print $out
  "/* Generated by src/doltgres/embed.pl; never edited by hand. */\n";
while (my ($name, $file) = splice(@pairs, 0, 2))
{
	open(my $in, '<:raw', $file) or die "cannot read $file: $!";
	my $data = do { local $/; <$in> };
	close($in);
	my @bytes = unpack('C*', $data);
	printf $out "\n/* %s is the bytes of %s. */\n", $name, basename($file);
	printf $out "static const unsigned char %s[%d] = {\n", $name,
	  scalar(@bytes);
	while (my @line = splice(@bytes, 0, 16))
	{
		print $out join(',', map { sprintf('0x%02x', $_) } @line), ",\n";
	}
	print $out "};\n";
}
close($out) or die "cannot write $output: $!";
