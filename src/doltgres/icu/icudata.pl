# Writes the C source that holds the vendored ICU's data archive (design item
# 12), so the data is compiled into every program that links ICU and nothing
# is installed or found at run time: the archive's bytes as 64-bit words
# under the name ICU looks its data up by, aligned as ICU requires.
#
# usage: icudata.pl <archive> <name> <output>

use strict;
use warnings FATAL => 'all';

my ($archive, $name, $output) = @ARGV;

open(my $in, '<:raw', $archive) or die "cannot read $archive: $!";
my $data = do { local $/; <$in> };
close($in);
$data .= "\0" x ((8 - length($data) % 8) % 8);
my @words = unpack('Q<*', $data);

open(my $out, '>', $output) or die "cannot write $output: $!";
binmode($out);
print $out "/* Generated by src/doltgres/icu/icudata.pl from the vendored ICU's data archive; never edited by hand. */\n";
print $out "#include <stdint.h>\n\n";
print $out "/* The archive is little-endian data, and its words are written as such. */\n";
print $out "#if defined(__BYTE_ORDER__) && __BYTE_ORDER__ != __ORDER_LITTLE_ENDIAN__\n";
print $out "#error \"the vendored ICU's data archive is little-endian\"\n";
print $out "#endif\n\n";
print $out "/* ICU looks the name up from its own sources, so no header declares it. */\n";
printf $out "extern const uint64_t %s[%d];\n\n", $name, scalar(@words);
printf $out "_Alignas(16) const uint64_t %s[%d] = {\n", $name, scalar(@words);
while (my @line = splice(@words, 0, 8))
{
	print $out join(',', map { sprintf('0x%xULL', $_) } @line), ",\n";
}
print $out "};\n";
close($out) or die "cannot write $output: $!";
